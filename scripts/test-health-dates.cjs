const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const code = ts.transpileModule(fs.readFileSync('src/healthDisplay.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const moduleUnderTest = { exports: {} };
new Function('exports', 'module', code)(moduleUnderTest.exports, moduleUnderTest);
const { healthDate, inspectionAlertDate, daysUntilInspection, inspectionSignal } = moduleUnderTest.exports;
const clock = new Date('2026-09-17T13:00:00Z');
const screenshotTicket = { visitDate: '', healthData: { 'Fecha Límite': '2026-09-18' } };
const alert = inspectionAlertDate(screenshotTicket);
assert.deepEqual(alert, { date: '2026-09-18', label: 'Reinspection deadline' });
assert.equal(inspectionSignal(daysUntilInspection(alert.date, clock)), 'red');
assert.equal(inspectionAlertDate({ ...screenshotTicket, visitDate: '2026-01-01' }).date, '2026-09-18');
assert.deepEqual(inspectionAlertDate({ visitDate: '2026-09-27', healthData: {} }), { date: '', label: 'Reinspection deadline' });
assert.equal(inspectionAlertDate({ visitDate: '2026-09-27', healthData: { 'Fecha Límite': '' } }).date, '');
assert.equal(inspectionAlertDate({ visitDate: '2026-09-27', healthData: { 'Fecha Límite': 'invalid' } }).date, '');
assert.equal(inspectionAlertDate({ visitDate: '', healthData: {} }).date, '');
assert.equal(healthDate('09/18/2026'), '2026-09-18');
assert.equal(healthDate('2026-09-18T00:00:00.000Z'), '2026-09-18');
assert.equal(healthDate('2026-02-30'), '');
assert.equal(healthDate('invalid'), '');
assert.equal(daysUntilInspection('2026-09-19', new Date('2026-09-18T02:00:00Z')), 2);
for (const [days, signal] of [[0, 'red'], [2, 'red'], [3, 'yellow'], [5, 'yellow'], [6, 'green'], [10, 'green'], [11, 'neutral']]) assert.equal(inspectionSignal(days), signal);
console.log('PASS: reinspection-only alerts, no inspection-date fallback, parsing, timezone and traffic-light boundaries');
